class Car {
    make: string;
    model: string;
    color: string;
    year: number;
    capacity: number;

    constructor(make: string, model: string, color: string, year: number, capacity: number) {
        this.make = make;
        this.model = model;
        this.color = color;
        this.year = year;
        this.capacity = capacity;
    }
}